# Evaluate model performance and calibration
def evaluate_model_performance(forecast, test_df):
    """
    Evaluate model performance and calibration of prediction intervals.

    Parameters:
    forecast: Forecast results
    test_df: Test data

    Returns:
    metrics: Dictionary with evaluation metrics
    """
    print("\n" + "="*60)
    print("MODEL EVALUATION")
    print("="*60)

    # Extract test period forecasts
    test_forecast = forecast.iloc[-len(test_df):].copy()

    # Calculate point forecast metrics
    mae = mean_absolute_error(test_forecast['y'], test_forecast['yhat'])
    rmse = np.sqrt(mean_squared_error(test_forecast['y'], test_forecast['yhat']))
    mape = np.mean(np.abs((test_forecast['y'] - test_forecast['yhat']) / test_forecast['y'])) * 100

    print(f"\n1. POINT FORECAST METRICS:")
    print(f"   - MAE (Mean Absolute Error): {mae:.2f}")
    print(f"   - RMSE (Root Mean Square Error): {rmse:.2f}")
    print(f"   - MAPE (Mean Absolute Percentage Error): {mape:.2f}%")

    # Calculate empirical coverage rates
    # For 80% interval
    coverage_80 = np.mean(
        (test_forecast['y'] >= test_forecast['yhat_lower_80']) &
        (test_forecast['y'] <= test_forecast['yhat_upper_80'])
    )

    # For 95% interval
    coverage_95 = np.mean(
        (test_forecast['y'] >= test_forecast['yhat_lower']) &
        (test_forecast['y'] <= test_forecast['yhat_upper'])
    )

    print(f"\n2. INITIAL CALIBRATION (Empirical Coverage):")
    print(f"   - 80% Prediction Interval Coverage: {coverage_80*100:.2f}% (Target: 80%)")
    print(f"   - 95% Prediction Interval Coverage: {coverage_95*100:.2f}% (Target: 95%)")

    # Calculate calibration error
    calibration_error_80 = abs(coverage_80 - 0.80) * 100
    calibration_error_95 = abs(coverage_95 - 0.95) * 100

    print(f"\n3. CALIBRATION ERRORS:")
    print(f"   - 80% Interval Error: {calibration_error_80:.2f}%")
    print(f"   - 95% Interval Error: {calibration_error_95:.2f}%")

    # Check if calibration is poor (error > 2%)
    needs_calibration = calibration_error_80 > 2 or calibration_error_95 > 2

    if needs_calibration:
        print(f"\n⚠️  Calibration needed: At least one interval error > 2%")
    else:
        print(f"\n✅ Calibration acceptable: All errors ≤ 2%")

    metrics = {
        'mae': mae,
        'rmse': rmse,
        'mape': mape,
        'coverage_80_initial': coverage_80,
        'coverage_95_initial': coverage_95,
        'calibration_error_80': calibration_error_80,
        'calibration_error_95': calibration_error_95,
        'needs_calibration': needs_calibration
    }

    return metrics, test_forecast

