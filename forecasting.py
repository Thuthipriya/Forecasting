# Generate synthetic time series dataset with daily frequency (2+ years)
def generate_synthetic_dataset():
    """
    Generate a synthetic time series dataset with:
    - Daily data for 2+ years (800+ days)
    - Multiple seasonal patterns (daily, weekly, yearly)
    - Trend component
    - External regressors (weather and economic indicators)
    - Noise
    """
    # Create date range: 800 days starting from 2022-01-01
    dates = pd.date_range(start='2022-01-01', periods=800, freq='D')

    # Base trend (linear with some changes)
    trend = np.linspace(100, 200, len(dates))

    # Add trend changepoints
    trend[300:500] += np.linspace(0, 50, 200)
    trend[500:] += np.linspace(50, 0, 300)

    # Seasonal patterns
    # Yearly seasonality (365-day cycle)
    yearly_season = 20 * np.sin(2 * np.pi * np.arange(len(dates)) / 365)

    # Weekly seasonality (7-day cycle)
    weekly_season = 10 * np.sin(2 * np.pi * np.arange(len(dates)) / 7)

    # Daily pattern (intra-day pattern approximated as 4 cycles per day)
    daily_season = 5 * np.sin(2 * np.pi * np.arange(len(dates)) / (1/4))

    # Generate external regressors
    # 1. Temperature (seasonal with noise)
    temperature = 15 + 10 * np.sin(2 * np.pi * np.arange(len(dates)) / 365) + np.random.normal(0, 3, len(dates))

    # 2. Economic indicator (slow-moving trend with some volatility)
    economic_indicator = np.cumsum(np.random.normal(0.01, 0.5, len(dates))) + 100

    # 3. Holiday indicator (spikes during "holiday" periods)
    holiday_effect = np.zeros(len(dates))
    for i in range(len(dates)):
        # Create synthetic holidays around specific dates
        if dates[i].month == 12 and dates[i].day <= 25 and dates[i].day >= 20:
            holiday_effect[i] = np.random.normal(15, 3)
        elif dates[i].month == 7 and dates[i].day <= 7 and dates[i].day >= 1:
            holiday_effect[i] = np.random.normal(10, 2)

    # Add special events/outliers
    outliers = np.zeros(len(dates))
    outlier_indices = random.sample(range(50, 750), 10)
    for idx in outlier_indices:
        outliers[idx] = np.random.normal(30, 10)

    # Combine all components with weights
    y = (trend +
         yearly_season +
         weekly_season +
         daily_season * 0.5 +  # Smaller daily effect
         temperature * 0.3 +  # Temperature effect
         economic_indicator * 0.1 +  # Economic effect
         holiday_effect +
         outliers +
         np.random.normal(0, 5, len(dates)))  # Random noise

    # Create DataFrame
    df = pd.DataFrame({
        'ds': dates,
        'y': y,
        'temperature': temperature,
        'economic_indicator': economic_indicator,
        'holiday_effect': holiday_effect,
        'is_holiday': (holiday_effect > 5).astype(int)
    })

    return df

