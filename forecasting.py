# Rolling origin cross-validation for time series
def rolling_origin_cv(df, initial_train_size=365, horizon=30, step=30):
    """
    Perform rolling origin cross-validation for time series.

    Parameters:
    df: Full dataset
    initial_train_size: Initial training window size in days
    horizon: Forecast horizon in days
    step: Step size between CV folds in days

    Returns:
    cv_results: DataFrame with CV metrics
    """
    cv_results = []
    total_points = len(df)

    print("\n" + "="*60)
    print("ROLLING ORIGIN CROSS-VALIDATION")
    print("="*60)

    fold_num = 1
    start_idx = initial_train_size

    while start_idx + horizon <= total_points:
        # Split train and validation
        train_cv = df.iloc[:start_idx].copy()
        val_cv = df.iloc[start_idx:start_idx + horizon].copy()

        # Initialize and fit Prophet model
        model_cv = Prophet(
            yearly_seasonality=True,
            weekly_seasonality=True,
            daily_seasonality=True,
            holidays=holiday_df,
            changepoint_prior_scale=0.05,  # Initial guess
            seasonality_prior_scale=10,
            holidays_prior_scale=10,
            seasonality_mode='additive'
        )

        # Add external regressors
        model_cv.add_regressor('temperature')
        model_cv.add_regressor('economic_indicator')

        # Fit model
        model_cv.fit(train_cv)

        # Create future dataframe for validation period
        future_cv = model_cv.make_future_dataframe(periods=horizon)
        future_cv = future_cv.merge(
            df[['ds', 'temperature', 'economic_indicator']],
            on='ds',
            how='left'
        )

        # Forecast
        forecast_cv = model_cv.predict(future_cv)

        # Extract validation predictions
        val_pred = forecast_cv.iloc[-horizon:][['ds', 'yhat', 'yhat_lower', 'yhat_upper']]
        val_actual = val_cv[['ds', 'y']]

        # Merge predictions with actuals
        val_results = pd.merge(val_pred, val_actual, on='ds')

        # Calculate metrics
        mae = mean_absolute_error(val_results['y'], val_results['yhat'])
        rmse = np.sqrt(mean_squared_error(val_results['y'], val_results['yhat']))

        # Store results
        cv_results.append({
            'fold': fold_num,
            'train_start': train_cv['ds'].min(),
            'train_end': train_cv['ds'].max(),
            'val_start': val_cv['ds'].min(),
            'val_end': val_cv['ds'].max(),
            'mae': mae,
            'rmse': rmse
        })

        print(f"Fold {fold_num}: Train: {train_cv['ds'].min().date()} to {train_cv['ds'].max().date()}, "
              f"Val: {val_cv['ds'].min().date()} to {val_cv['ds'].max().date()}, "
              f"MAE: {mae:.2f}, RMSE: {rmse:.2f}")

        fold_num += 1
        start_idx += step

    cv_results_df = pd.DataFrame(cv_results)

    print(f"\nCross-validation completed: {len(cv_results)} folds")
    print(f"Average MAE: {cv_results_df['mae'].mean():.2f}")
    print(f"Average RMSE: {cv_results_df['rmse'].mean():.2f}")

    return cv_results_df

