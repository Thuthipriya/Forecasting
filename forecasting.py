# Visualize forecasting results
def visualize_results(train_df, test_df, forecast, calibrated_forecast, metrics, calibration_info):
    """
    Create comprehensive visualizations of forecasting results.

    Parameters:
    train_df: Training data
    test_df: Test data
    forecast: Forecast results
    calibrated_forecast: Calibrated forecast
    metrics: Evaluation metrics
    calibration_info: Calibration information
    """

    fig = plt.figure(figsize=(18, 12))

    # 1. Full forecast with intervals
    ax1 = plt.subplot(3, 2, 1)
    ax1.plot(train_df['ds'], train_df['y'], 'b-', alpha=0.7, label='Training Data')
    ax1.plot(test_df['ds'], test_df['y'], 'g-', alpha=0.7, label='Actual Test Data')
    ax1.plot(forecast['ds'], forecast['yhat'], 'r--', alpha=0.9, label='Forecast')

    # Plot 95% prediction intervals
    ax1.fill_between(
        forecast['ds'],
        forecast['yhat_lower'],
        forecast['yhat_upper'],
        alpha=0.2, color='red', label='95% Prediction Interval'
    )

    ax1.set_title('Full Time Series Forecast with 95% Prediction Intervals')
    ax1.set_xlabel('Date')
    ax1.set_ylabel('Value')
    ax1.legend(loc='upper left')
    ax1.grid(True, alpha=0.3)

    # 2. Test period zoom with calibrated intervals
    ax2 = plt.subplot(3, 2, 2)
    test_dates = calibrated_forecast['ds']

    ax2.plot(test_dates, calibrated_forecast['y'], 'g-', alpha=0.9, label='Actual', linewidth=2)
    ax2.plot(test_dates, calibrated_forecast['yhat'], 'r--', alpha=0.9, label='Forecast', linewidth=2)

    # Plot calibrated intervals if available
    if 'yhat_lower_95_calibrated' in calibrated_forecast.columns:
        ax2.fill_between(
            test_dates,
            calibrated_forecast['yhat_lower_95_calibrated'],
            calibrated_forecast['yhat_upper_95_calibrated'],
            alpha=0.2, color='orange', label='Calibrated 95% Interval'
        )
    else:
        ax2.fill_between(
            test_dates,
            calibrated_forecast['yhat_lower'],
            calibrated_forecast['yhat_upper'],
            alpha=0.2, color='red', label='95% Interval'
        )

    ax2.set_title('Test Period: Actual vs Forecast with Intervals')
    ax2.set_xlabel('Date')
    ax2.set_ylabel('Value')
    ax2.legend(loc='upper left')
    ax2.grid(True, alpha=0.3)

    # 3. Coverage comparison
    ax3 = plt.subplot(3, 2, 3)
    coverages = ['80%', '95%']
    initial_coverages = [metrics['coverage_80_initial']*100, metrics['coverage_95_initial']*100]
    calibrated_coverages = [calibration_info['coverage_80_calibrated']*100,
                           calibration_info['coverage_95_calibrated']*100]
    target_coverages = [80, 95]

    x = np.arange(len(coverages))
    width = 0.25

    ax3.bar(x - width, initial_coverages, width, label='Initial', color='skyblue')
    ax3.bar(x, calibrated_coverages, width, label='Calibrated', color='lightgreen')
    ax3.bar(x + width, target_coverages, width, label='Target', color='orange', alpha=0.6)

    ax3.set_xlabel('Prediction Interval')
    ax3.set_ylabel('Empirical Coverage (%)')
    ax3.set_title('Coverage Rates: Initial vs Calibrated vs Target')
    ax3.set_xticks(x)
    ax3.set_xticklabels(coverages)
    ax3.legend()
    ax3.grid(True, alpha=0.3)

    # Add value labels
    for i, (init, cal) in enumerate(zip(initial_coverages, calibrated_coverages)):
        ax3.text(i - width, init + 1, f'{init:.1f}%', ha='center', va='bottom', fontsize=9)
        ax3.text(i, cal + 1, f'{cal:.1f}%', ha='center', va='bottom', fontsize=9)

    # 4. Residual analysis
    ax4 = plt.subplot(3, 2, 4)
    residuals = calibrated_forecast['y'] - calibrated_forecast['yhat']
    ax4.scatter(calibrated_forecast['yhat'], residuals, alpha=0.6, color='purple')
    ax4.axhline