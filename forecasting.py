# Prepare data for Prophet
def prepare_prophet_data(df, train_test_split=0.8):
    """
    Prepare data for Prophet modeling with train-test split.

    Parameters:
    df: DataFrame with time series data
    train_test_split: Proportion of data for training

    Returns:
    train_df, test_df, full_df formatted for Prophet
    """
    # Prophet requires columns named 'ds' (datetime) and 'y' (target)
    prophet_train_df = df[['ds', 'y']].copy()

    # Add external regressors
    prophet_train_df['temperature'] = df['temperature']
    prophet_train_df['economic_indicator'] = df['economic_indicator']

    # Split into train and test
    split_idx = int(len(prophet_train_df) * train_test_split)
    train_df = prophet_train_df.iloc[:split_idx].copy()
    test_df = prophet_train_df.iloc[split_idx:].copy()

    # Create holiday dataframe
    holiday_df = df[df['is_holiday'] == 1][['ds']].copy()
    holiday_df['holiday'] = 'synthetic_holiday'

    print(f"\nTrain set size: {len(train_df)} days ({train_df['ds'].min()} to {train_df['ds'].max()})")
    print(f"Test set size: {len(test_df)} days ({test_df['ds'].min()} to {test_df['ds'].max()})")

    return train_df, test_df, holiday_df

