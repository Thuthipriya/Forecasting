def train_final_model(train_df, test_df, holiday_df, best_params):
    """
    Train final Prophet model with tuned hyperparameters.

    Parameters:
    train_df: Training data
    test_df: Test data
    holiday_df: Holiday data
    best_params: Best hyperparameters from tuning

    Returns:
    model: Trained Prophet model
    forecast: Forecast results
    """
    print("\n" + "="*60)
    print("TRAINING FINAL MODEL")
    print("="*60)

    # Initialize model with best parameters
    model = Prophet(
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=True,
        holidays=holiday_df,
        changepoint_prior_scale=best_params['changepoint_prior_scale'],
        seasonality_prior_scale=best_params['seasonality_prior_scale'],
        holidays_prior_scale=best_params['holidays_prior_scale'],
        seasonality_mode=best_params['seasonality_mode'],
        interval_width=0.95,  # For 95% prediction intervals
        mcmc_samples=0  # Set to 300 for full uncertainty estimation (slower)
    )

    # Add external regressors
    model.add_regressor('temperature')
    model.add_regressor('economic_indicator')

    # Fit model on full training data
    print("Fitting model...")
    model.fit(train_df)

    # Create future dataframe for test period
    future = model.make_future_dataframe(periods=len(test_df))

    # Add external regressors to future dataframe
    future_test = test_df[['ds', 'temperature', 'economic_indicator']].copy()
    future_test.columns = ['ds', 'temperature', 'economic_indicator']
    future = future.merge(future_test, on='ds', how='left')

    # Fill any missing values in regressors
    future['temperature'] = future['temperature'].fillna(future['temperature'].mean())
    future['economic_indicator'] = future['economic_indicator'].fillna(future['economic_indicator'].mean())

    # Generate forecast
    print("Generating forecasts...")
    forecast = model.predict(future)

    # Add actual values to forecast for comparison
    forecast = forecast.merge(
        pd.concat([train_df[['ds', 'y']], test_df[['ds', 'y']]]),
        on='ds',
        how='left'
    )

    # Calculate 80% prediction intervals (Prophet provides 95% by default)
    # We'll compute 80% intervals based on the standard deviation
    forecast['yhat_lower_80'] = forecast['yhat'] - 1.28 * (forecast['yhat_upper'] - forecast['yhat_lower']) / (2 * 1.96)
    forecast['yhat_upper_80'] = forecast['yhat'] + 1.28 * (forecast['yhat_upper'] - forecast['yhat_lower']) / (2 * 1.96)

    print("Model training complete!")

    return model, forecast

