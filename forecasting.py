# Hyperparameter tuning
def tune_prophet_hyperparameters(train_df, holiday_df, n_iterations=20):
    """
    Tune Prophet hyperparameters using simple grid search.

    Parameters:
    train_df: Training data
    holiday_df: Holiday data
    n_iterations: Number of parameter combinations to try

    Returns:
    best_params: Best hyperparameters
    """
    # Parameter grid
    param_grid = {
        'changepoint_prior_scale': [0.001, 0.01, 0.05, 0.1, 0.5],
        'seasonality_prior_scale': [1, 5, 10, 20, 30],
        'holidays_prior_scale': [1, 5, 10, 20],
        'seasonality_mode': ['additive', 'multiplicative']
    }

    # Split for validation during tuning
    tune_train = train_df.iloc[:int(len(train_df) * 0.8)]
    tune_val = train_df.iloc[int(len(train_df) * 0.8):]

    best_score = float('inf')
    best_params = None
    results = []

    print("\n" + "="*60)
    print("HYPERPARAMETER TUNING")
    print("="*60)

    # Simple random search
    for i in range(n_iterations):
        # Randomly sample parameters
        params = {
            'changepoint_prior_scale': np.random.choice(param_grid['changepoint_prior_scale']),
            'seasonality_prior_scale': np.random.choice(param_grid['seasonality_prior_scale']),
            'holidays_prior_scale': np.random.choice(param_grid['holidays_prior_scale']),
            'seasonality_mode': np.random.choice(param_grid['seasonality_mode'])
        }

        try:
            # Initialize model with current parameters
            model_tune = Prophet(
                yearly_seasonality=True,
                weekly_seasonality=True,
                daily_seasonality=True,
                holidays=holiday_df,
                changepoint_prior_scale=params['changepoint_prior_scale'],
                seasonality_prior_scale=params['seasonality_prior_scale'],
                holidays_prior_scale=params['holidays_prior_scale'],
                seasonality_mode=params['seasonality_mode']
            )

            # Add external regressors
            model_tune.add_regressor('temperature')
            model_tune.add_regressor('economic_indicator')

            # Fit on training portion
            model_tune.fit(tune_train)

            # Create future dataframe
            future_tune = model_tune.make_future_dataframe(periods=len(tune_val))
            future_tune = future_tune.merge(
                train_df[['ds', 'temperature', 'economic_indicator']],
                on='ds',
                how='left'
            )

            # Predict
            forecast_tune = model_tune.predict(future_tune)

            # Extract validation predictions
            val_pred = forecast_tune.iloc[-len(tune_val):]['yhat'].values
            val_actual = tune_val['y'].values

            # Calculate RMSE
            rmse = np.sqrt(mean_squared_error(val_actual, val_pred))

            results.append({
                'iteration': i + 1,
                'params': params,
                'rmse': rmse
            })

            print(f"Iteration {i+1}: RMSE = {rmse:.2f}, Params = {params}")

            # Update best parameters
            if rmse < best_score:
                best_score = rmse
                best_params = params

        except Exception as e:
            print(f"Iteration {i+1} failed: {e}")
            continue

    results_df = pd.DataFrame(results)
    print(f"\nBest RMSE: {best_score:.2f}")
    print(f"Best parameters: {best_params}")

    return best_params

# Tune hyperparameters
