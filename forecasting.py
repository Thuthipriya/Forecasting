# Implement calibration using isotonic regression
def calibrate_prediction_intervals(model, forecast, train_df, test_forecast):
    """
    Calibrate prediction intervals using isotonic regression on residuals.

    Parameters:
    model: Trained Prophet model
    forecast: Forecast results
    train_df: Training data
    test_forecast: Test forecast results

    Returns:
    calibrated_forecast: Forecast with calibrated intervals
    calibration_info: Information about calibration process
    """
    print("\n" + "="*60)
    print("MODEL CALIBRATION")
    print("="*60)

    # Calculate residuals on training data
    train_forecast = forecast.iloc[:len(train_df)].copy()
    train_residuals = train_forecast['y'] - train_forecast['yhat']

    # Calculate standard deviation of residuals
    residual_std = train_residuals.std()

    # Get uncertainty from model (standard deviation of predictions)
    train_uncertainty = (train_forecast['yhat_upper'] - train_forecast['yhat_lower']) / (2 * 1.96)

    # Calculate normalized residuals (residual divided by uncertainty)
    normalized_residuals = train_residuals / train_uncertainty

    # Sort for isotonic regression
    sorted_indices = np.argsort(normalized_residuals)
    sorted_residuals = normalized_residuals.iloc[sorted_indices].values

    # Create empirical quantiles
    n = len(sorted_residuals)
    empirical_quantiles = np.arange(1, n + 1) / (n + 1)

    # Fit isotonic regression
    iso_reg = IsotonicRegression(out_of_bounds='clip')
    iso_reg.fit(sorted_residuals, stats.norm.ppf(empirical_quantiles))

    # Apply calibration to test set
    test_uncertainty = (test_forecast['yhat_upper'] - test_forecast['yhat_lower']) / (2 * 1.96)

    # Get calibrated z-scores for different confidence levels
    calibrated_z_80 = iso_reg.predict([0])[0] * 1.28 / stats.norm.ppf(0.9)
    calibrated_z_95 = iso_reg.predict([0])[0] * 1.96 / stats.norm.ppf(0.975)

    # Calculate calibrated intervals
    calibrated_forecast = test_forecast.copy()

    # For 80% interval
    calibrated_forecast['yhat_lower_80_calibrated'] = (
        calibrated_forecast['yhat'] - calibrated_z_80 * test_uncertainty
    )
    calibrated_forecast['yhat_upper_80_calibrated'] = (
        calibrated_forecast['yhat'] + calibrated_z_80 * test_uncertainty
    )

    # For 95% interval
    calibrated_forecast['yhat_lower_95_calibrated'] = (
        calibrated_forecast['yhat'] - calibrated_z_95 * test_uncertainty
    )
    calibrated_forecast['yhat_upper_95_calibrated'] = (
        calibrated_forecast['yhat'] + calibrated_z_95 * test_uncertainty
    )

    # Calculate calibrated coverage
    coverage_80_calibrated = np.mean(
        (calibrated_forecast['y'] >= calibrated_forecast['yhat_lower_80_calibrated']) &
        (calibrated_forecast['y'] <= calibrated_forecast['yhat_upper_80_calibrated'])
    )

    coverage_95_calibrated = np.mean(
        (calibrated_forecast['y'] >= calibrated_forecast['yhat_lower_95_calibrated']) &
        (calibrated_forecast['y'] <= calibrated_forecast['yhat_upper_95_calibrated'])
    )

    print(f"\nCalibration Results:")
    print(f"  - Calibrated 80% Interval Coverage: {coverage_80_calibrated*100:.2f}% (Target: 80%)")
    print(f"  - Calibrated 95% Interval Coverage: {coverage_95_calibrated*100:.2f}% (Target: 95%)")

    # Calculate improvement
    improvement_80 = abs(coverage_80_calibrated - 0.80) * 100
    improvement_95 = abs(coverage_95_calibrated - 0.95) * 100

    print(f"\nCalibration Improvement:")
    print(f"  - 80% Interval Error after calibration: {improvement_80:.2f}%")
    print(f"  - 95% Interval Error after calibration: {improvement_95:.2f}%")

    calibration_info = {
        'coverage_80_calibrated': coverage_80_calibrated,
        'coverage_95_calibrated': coverage_95_calibrated,
        'calibrated_z_80': calibrated_z_80,
        'calibrated_z_95': calibrated_z_95,
        'improvement_80': improvement_80,
        'improvement_95': improvement_95
    }

    return calibrated_forecast, calibration_info

