def calibrate_prediction_intervals_simple(train_df, forecast, test_forecast):
    """Simple but effective calibration using residual quantiles."""

    print("\n" + "="*60)
    print("MODEL CALIBRATION (Quantile Method)")
    print("="*60)

    # Calculate residuals on training data
    train_forecast = forecast.iloc[:len(train_df)].copy()
    train_residuals = train_forecast['y'] - train_forecast['yhat']

    # Calculate residual statistics
    residual_mean = train_residuals.mean()
    residual_std = train_residuals.std()

    print(f"\nResidual Statistics:")
    print(f"  Mean: {residual_mean:.2f}")
    print(f"  Std:  {residual_std:.2f}")

    # Method 1: Simple scaling based on empirical coverage
    # Calculate what coverage we actually got on training data
    train_coverage_80 = np.mean(
        (train_forecast['y'] >= train_forecast['yhat_lower_80']) &
        (train_forecast['y'] <= train_forecast['yhat_upper_80'])
    )

    train_coverage_95 = np.mean(
        (train_forecast['y'] >= train_forecast['yhat_lower_95']) &
        (train_forecast['y'] <= train_forecast['yhat_upper_95'])
    )

    print(f"\nTraining Data Coverage:")
    print(f"  80% intervals: {train_coverage_80*100:.1f}%")
    print(f"  95% intervals: {train_coverage_95*100:.1f}%")

    # Method 2: Quantile-based calibration
    # Get empirical quantiles from absolute residuals
    abs_residuals = np.abs(train_residuals)
    empirical_80 = np.percentile(abs_residuals, 80)  # 80th percentile
    empirical_95 = np.percentile(abs_residuals, 95)  # 95th percentile

    # Current interval widths (from Prophet)
    current_width_80 = (test_forecast['yhat_upper_80'] - test_forecast['yhat_lower_80']).mean() / 2
    current_width_95 = (test_forecast['yhat_upper_95'] - test_forecast['yhat_lower_95']).mean() / 2

    # Calculate scaling factors
    scale_80 = empirical_80 / current_width_80 if current_width_80 > 0 else 1.5
    scale_95 = empirical_95 / current_width_95 if current_width_95 > 0 else 1.8

    # Apply calibration
    calibrated = test_forecast.copy()

    # Center the intervals on the prediction
    calibrated['yhat_lower_80_cal'] = calibrated['yhat'] - scale_80 * current_width_80
    calibrated['yhat_upper_80_cal'] = calibrated['yhat'] + scale_80 * current_width_80

    calibrated['yhat_lower_95_cal'] = calibrated['yhat'] - scale_95 * current_width_95
    calibrated['yhat_upper_95_cal'] = calibrated['yhat'] + scale_95 * current_width_95

    # Calculate calibrated coverage
    coverage_80_cal = np.mean(
        (calibrated['y'] >= calibrated['yhat_lower_80_cal']) &
        (calibrated['y'] <= calibrated['yhat_upper_80_cal'])
    )

    coverage_95_cal = np.mean(
        (calibrated['y'] >= calibrated['yhat_lower_95_cal']) &
        (calibrated['y'] <= calibrated['yhat_upper_95_cal'])
    )

    print(f"\nCalibration Results:")
    print(f"  Scaling factors - 80%: {scale_80:.2f}, 95%: {scale_95:.2f}")
    print(f"  Calibrated 80% Coverage: {coverage_80_cal*100:.1f}%")
    print(f"  Calibrated 95% Coverage: {coverage_95_cal*100:.1f}%")

    # Calculate improvements
    improvement_80 = abs(metrics['error_80'] - abs(coverage_80_cal - 0.80) * 100)
    improvement_95 = abs(metrics['error_95'] - abs(coverage_95_cal - 0.95) * 100)

    print(f"\nImprovement:")
    print(f"  80% error reduced by: {improvement_80:.1f}%")
    print(f"  95% error reduced by: {improvement_95:.1f}%")

    calibration_info = {
        'coverage_80_calibrated': coverage_80_cal,
        'coverage_95_calibrated': coverage_95_cal,
        'scale_80': scale_80,
        'scale_95': scale_95,
        'improvement_80': improvement_80,
        'improvement_95': improvement_95,
        'method': 'quantile_scaling'
    }

    return calibrated, calibration_info

# Apply calibration if needed
