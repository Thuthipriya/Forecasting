def generate_better_synthetic_dataset():
    """
    Generate a MORE REALISTIC synthetic time series dataset with:
    - Daily data for 2+ years (800+ days)
    - Clear seasonal patterns (yearly, weekly)
    - External regressors with proper relationships
    - Reasonable noise levels
    """
    print("Generating improved synthetic dataset...")

    # Create date range: 800 days starting from 2022-01-01
    dates = pd.date_range(start='2022-01-01', periods=800, freq='D')

    # 1. Linear trend with one changepoint
    trend = np.linspace(100, 200, len(dates))
    # Add a changepoint at day 400
    trend[400:] += np.linspace(0, 30, 400)

    # 2. Clear yearly seasonality (365.25 days for leap years)
    day_of_year = dates.dayofyear + (dates.hour / 24)
    yearly_season = 25 * np.sin(2 * np.pi * day_of_year / 365.25)

    # 3. Weekly seasonality
    day_of_week = dates.dayofweek + (dates.hour / 24)
    weekly_season = 15 * np.sin(2 * np.pi * day_of_week / 7)

    # 4. Generate external regressors with proper relationships
    # Temperature (correlated with yearly seasonality)
    temperature = 15 + 12 * np.sin(2 * np.pi * day_of_year / 365.25) + np.random.normal(0, 5, len(dates))

    # Economic indicator (slow trend with some correlation to target)
    economic = 100 + np.cumsum(np.random.normal(0.05, 0.3, len(dates)))

    # 5. Holiday effects (more realistic)
    holiday_effect = np.zeros(len(dates))
    # December holidays
    dec_mask = (dates.month == 12) & (dates.day >= 20) & (dates.day <= 27)
    holiday_effect[dec_mask] = np.random.normal(25, 5, dec_mask.sum())
    # July holidays
    jul_mask = (dates.month == 7) & (dates.day >= 1) & (dates.day <= 7)
    holiday_effect[jul_mask] = np.random.normal(20, 4, jul_mask.sum())

    # 6. Add a few outliers (but not too many)
    outliers = np.zeros(len(dates))
    outlier_indices = random.sample(range(100, 700), 8)  # Fewer outliers
    for idx in outlier_indices:
        outliers[idx] = np.random.normal(40, 15)  # Smaller outliers

    # 7. Combine with realistic weights
    y = (
        trend * 1.0 +
        yearly_season * 1.0 +
        weekly_season * 0.7 +
        temperature * 0.4 +      # Temperature has moderate effect
        economic * 0.3 +         # Economic indicator has smaller effect
        holiday_effect * 1.0 +
        outliers +
        np.random.normal(0, 8, len(dates))  # Moderate noise
    )

    # Create DataFrame
    df = pd.DataFrame({
        'ds': dates,
        'y': y,
        'temperature': temperature,
        'economic': economic,
        'holiday_effect': holiday_effect,
        'is_holiday': ((holiday_effect > 10) | dec_mask | jul_mask).astype(int)
    })

    print(f"Dataset generated: {len(df)} days")
    print(f"Date range: {df['ds'].min()} to {df['ds'].max()}")
    return df

# Generate the improved dataset
synthetic_df = generate_better_synthetic_dataset()

