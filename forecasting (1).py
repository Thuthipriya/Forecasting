def prepare_prophet_data(df, train_test_split=0.8):
    """Prepare data for Prophet modeling."""

    # Prophet requires columns 'ds' and 'y'
    prophet_df = df[['ds', 'y']].copy()
    prophet_df['temperature'] = df['temperature']
    prophet_df['economic'] = df['economic']

    # Split into train and test
    split_idx = int(len(prophet_df) * train_test_split)
    train_df = prophet_df.iloc[:split_idx].copy()
    test_df = prophet_df.iloc[split_idx:].copy()

    # Create holiday dataframe
    holiday_df = df[df['is_holiday'] == 1][['ds']].copy()
    holiday_df['holiday'] = 'synthetic_holiday'

    print(f"\nData Preparation:")
    print(f"  Train set: {len(train_df)} days ({train_df['ds'].min().date()} to {train_df['ds'].max().date()})")
    print(f"  Test set:  {len(test_df)} days ({test_df['ds'].min().date()} to {test_df['ds'].max().date()})")
    print(f"  Holidays:  {len(holiday_df)} days identified")

    return train_df, test_df, holiday_df

