def tune_hyperparameters(train_df, holiday_df, n_iterations=10):
    """Tune Prophet hyperparameters using simple random search."""

    print("\n" + "="*60)
    print("HYPERPARAMETER TUNING")
    print("="*60)

    # Parameter grid
    param_grid = {
        'changepoint_prior_scale': [0.01, 0.05, 0.1, 0.5],
        'seasonality_prior_scale': [5, 10, 20],
        'holidays_prior_scale': [5, 10, 20],
        'seasonality_mode': ['additive']
    }

    # Split for validation
    tune_train = train_df.iloc[:int(len(train_df) * 0.7)]
    tune_val = train_df.iloc[int(len(train_df) * 0.7):]

    best_score = float('inf')
    best_params = None
    results = []

    for i in range(n_iterations):
        # Sample parameters
        params = {
            'changepoint_prior_scale': np.random.choice(param_grid['changepoint_prior_scale']),
            'seasonality_prior_scale': np.random.choice(param_grid['seasonality_prior_scale']),
            'holidays_prior_scale': np.random.choice(param_grid['holidays_prior_scale']),
            'seasonality_mode': np.random.choice(param_grid['seasonality_mode'])
        }

        try:
            # Initialize model
            model_tune = Prophet(
                yearly_seasonality=True,
                weekly_seasonality=True,
                daily_seasonality=False,
                holidays=holiday_df,
                changepoint_prior_scale=params['changepoint_prior_scale'],
                seasonality_prior_scale=params['seasonality_prior_scale'],
                holidays_prior_scale=params['holidays_prior_scale'],
                seasonality_mode=params['seasonality_mode'],
                interval_width=0.80
            )

            model_tune.add_regressor('temperature')
            model_tune.add_regressor('economic')

            # Fit and predict
            model_tune.fit(tune_train)
            future_tune = model_tune.make_future_dataframe(periods=len(tune_val))
            future_tune = future_tune.merge(
                train_df[['ds', 'temperature', 'economic']],
                on='ds',
                how='left'
            )
            forecast_tune = model_tune.predict(future_tune)

            # Calculate metrics
            val_pred = forecast_tune.iloc[-len(tune_val):]['yhat'].values
            val_actual = tune_val['y'].values
            rmse = np.sqrt(mean_squared_error(val_actual, val_pred))

            # Store results
            results.append({
                'iteration': i + 1,
                'params': params,
                'rmse': rmse
            })

            print(f"Iteration {i+1}: RMSE = {rmse:.2f}")

            # Update best
            if rmse < best_score:
                best_score = rmse
                best_params = params

        except Exception as e:
            print(f"Iteration {i+1} failed: {str(e)[:50]}...")
            continue

    # If tuning failed, use reasonable defaults
    if best_params is None:
        best_params = {
            'changepoint_prior_scale': 0.05,
            'seasonality_prior_scale': 10,
            'holidays_prior_scale': 10,
            'seasonality_mode': 'additive'
        }
        print("Using default parameters")
    else:
        print(f"\nBest RMSE: {best_score:.2f}")
        print(f"Best parameters: {best_params}")

    return best_params

best_params = tune_hyperparameters(train_df, holiday_df, n_iterations=8)

