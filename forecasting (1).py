def rolling_origin_cv(train_df, holiday_df, initial_days=365, horizon=30, step=30):
    """Perform rolling origin cross-validation for time series."""

    print("\n" + "="*60)
    print("ROLLING ORIGIN CROSS-VALIDATION")
    print("="*60)

    cv_results = []
    total_points = len(train_df)
    fold_num = 1
    start_idx = initial_days

    while start_idx + horizon <= total_points:
        # Split train and validation
        train_cv = train_df.iloc[:start_idx].copy()
        val_cv = train_df.iloc[start_idx:start_idx + horizon].copy()

        # Initialize Prophet model
        model_cv = Prophet(
            yearly_seasonality=True,
            weekly_seasonality=True,
            daily_seasonality=False,  # Daily too noisy for daily data
            holidays=holiday_df,
            changepoint_prior_scale=0.05,
            seasonality_prior_scale=10,
            holidays_prior_scale=10,
            seasonality_mode='additive',
            interval_width=0.80  # For 80% intervals
        )

        # Add external regressors
        model_cv.add_regressor('temperature')
        model_cv.add_regressor('economic')

        # Fit model
        model_cv.fit(train_cv)

        # Create future dataframe
        future_cv = model_cv.make_future_dataframe(periods=horizon)
        future_cv = future_cv.merge(
            train_df[['ds', 'temperature', 'economic']],
            on='ds',
            how='left'
        )

        # Forecast
        forecast_cv = model_cv.predict(future_cv)

        # Extract validation predictions
        val_pred = forecast_cv.iloc[-horizon:][['ds', 'yhat', 'yhat_lower', 'yhat_upper']]
        val_actual = val_cv[['ds', 'y']]

        # Merge and calculate metrics
        val_results = pd.merge(val_pred, val_actual, on='ds')
        mae = mean_absolute_error(val_results['y'], val_results['yhat'])
        rmse = np.sqrt(mean_squared_error(val_results['y'], val_results['yhat']))

        # Calculate coverage for 80% interval
        coverage_80 = np.mean(
            (val_results['y'] >= val_results['yhat_lower']) &
            (val_results['y'] <= val_results['yhat_upper'])
        )

        cv_results.append({
            'fold': fold_num,
            'train_start': train_cv['ds'].min().date(),
            'train_end': train_cv['ds'].max().date(),
            'val_start': val_cv['ds'].min().date(),
            'val_end': val_cv['ds'].max().date(),
            'mae': mae,
            'rmse': rmse,
            'coverage_80': coverage_80
        })

        print(f"Fold {fold_num}: Train: {train_cv['ds'].min().date()} to {train_cv['ds'].max().date()}, "
              f"Val: {val_cv['ds'].min().date()} to {val_cv['ds'].max().date()}, "
              f"MAE: {mae:.2f}, Coverage: {coverage_80*100:.1f}%")

        fold_num += 1
        start_idx += step

    cv_results_df = pd.DataFrame(cv_results)

    print(f"\nCross-validation Summary:")
    print(f"  Folds completed: {len(cv_results)}")
    print(f"  Average MAE: {cv_results_df['mae'].mean():.2f}")
    print(f"  Average RMSE: {cv_results_df['rmse'].mean():.2f}")
    print(f"  Average 80% Coverage: {cv_results_df['coverage_80'].mean()*100:.1f}%")

    return cv_results_df

# Run cross-validation
cv_results = rolling_origin_cv(train_df, holiday_df, initial_days=365, horizon=60, step=30)

