def evaluate_model_performance(forecast, test_df):
    """Evaluate model performance and calibration."""

    print("\n" + "="*60)
    print("MODEL EVALUATION")
    print("="*60)

    # Extract test period
    test_forecast = forecast.iloc[-len(test_df):].copy()

    # Calculate point forecast metrics
    mae = mean_absolute_error(test_forecast['y'], test_forecast['yhat'])
    rmse = np.sqrt(mean_squared_error(test_forecast['y'], test_forecast['yhat']))
    mape = np.mean(np.abs((test_forecast['y'] - test_forecast['yhat']) / test_forecast['y'])) * 100

    print("\n1. POINT FORECAST METRICS:")
    print(f"   - MAE:  {mae:.2f}")
    print(f"   - RMSE: {rmse:.2f}")
    print(f"   - MAPE: {mape:.1f}%")

    # Calculate empirical coverage
    coverage_80 = np.mean(
        (test_forecast['y'] >= test_forecast['yhat_lower_80']) &
        (test_forecast['y'] <= test_forecast['yhat_upper_80'])
    )

    coverage_95 = np.mean(
        (test_forecast['y'] >= test_forecast['yhat_lower_95']) &
        (test_forecast['y'] <= test_forecast['yhat_upper_95'])
    )

    print("\n2. INITIAL CALIBRATION (Empirical Coverage):")
    print(f"   - 80% Prediction Interval: {coverage_80*100:.1f}% (Target: 80%)")
    print(f"   - 95% Prediction Interval: {coverage_95*100:.1f}% (Target: 95%)")

    # Calculate calibration errors
    error_80 = abs(coverage_80 - 0.80) * 100
    error_95 = abs(coverage_95 - 0.95) * 100

    print("\n3. CALIBRATION ERRORS:")
    print(f"   - 80% Interval Error: {error_80:.1f}%")
    print(f"   - 95% Interval Error: {error_95:.1f}%")

    # Check if calibration needed
    needs_calibration = error_80 > 2 or error_95 > 2

    if needs_calibration:
        print(f"\n⚠️  Calibration needed: Errors > 2%")
    else:
        print(f"\n✅ Calibration acceptable")

    metrics = {
        'mae': mae,
        'rmse': rmse,
        'mape': mape,
        'coverage_80_initial': coverage_80,
        'coverage_95_initial': coverage_95,
        'error_80': error_80,
        'error_95': error_95,
        'needs_calibration': needs_calibration
    }

    return metrics, test_forecast

metrics, test_forecast = evaluate_model_performance(forecast, test_df)

