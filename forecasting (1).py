def train_final_model(train_df, test_df, holiday_df, best_params):
    """Train final Prophet model with tuned parameters."""

    print("\n" + "="*60)
    print("TRAINING FINAL MODEL")
    print("="*60)

    # Train TWO models: one for 80% intervals, one for 95% intervals
    print("Training model for 80% prediction intervals...")
    model_80 = Prophet(
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=False,
        holidays=holiday_df,
        changepoint_prior_scale=best_params['changepoint_prior_scale'],
        seasonality_prior_scale=best_params['seasonality_prior_scale'],
        holidays_prior_scale=best_params['holidays_prior_scale'],
        seasonality_mode=best_params['seasonality_mode'],
        interval_width=0.80,  # 80% intervals
        uncertainty_samples=1000
    )

    print("Training model for 95% prediction intervals...")
    model_95 = Prophet(
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=False,
        holidays=holiday_df,
        changepoint_prior_scale=best_params['changepoint_prior_scale'],
        seasonality_prior_scale=best_params['seasonality_prior_scale'],
        holidays_prior_scale=best_params['holidays_prior_scale'],
        seasonality_mode=best_params['seasonality_mode'],
        interval_width=0.95,  # 95% intervals
        uncertainty_samples=1000
    )

    # Add regressors to both models
    for model in [model_80, model_95]:
        model.add_regressor('temperature')
        model.add_regressor('economic')

    # Fit both models
    model_80.fit(train_df)
    model_95.fit(train_df)

    # Create future dataframes
    future = model_80.make_future_dataframe(periods=len(test_df))
    future = future.merge(
        test_df[['ds', 'temperature', 'economic']],
        on='ds',
        how='left'
    )

    # Fill missing values
    for col in ['temperature', 'economic']:
        future[col] = future[col].fillna(future[col].mean())

    # Generate forecasts
    print("Generating forecasts...")
    forecast_80 = model_80.predict(future)
    forecast_95 = model_95.predict(future)

    # Combine forecasts
    forecast = forecast_80[['ds', 'yhat', 'yhat_lower', 'yhat_upper']].copy()
    forecast.rename(columns={
        'yhat_lower': 'yhat_lower_80',
        'yhat_upper': 'yhat_upper_80'
    }, inplace=True)

    # Add 95% intervals
    forecast['yhat_lower_95'] = forecast_95['yhat_lower']
    forecast['yhat_upper_95'] = forecast_95['yhat_upper']

    # Add actual values
    all_actual = pd.concat([train_df[['ds', 'y']], test_df[['ds', 'y']]])
    forecast = forecast.merge(all_actual, on='ds', how='left')

    print("Model training complete!")

    return model_80, model_95, forecast

model_80, model_95, forecast = train_final_model(train_df, test_df, holiday_df, best_params)

