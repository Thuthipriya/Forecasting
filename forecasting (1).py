def visualize_results(train_df, test_df, forecast, calibrated_forecast, metrics, calibration_info):
    """Create comprehensive visualizations."""

    print("\n" + "="*60)
    print("GENERATING VISUALIZATIONS")
    print("="*60)

    fig = plt.figure(figsize=(16, 12))

    # 1. Full forecast with intervals
    ax1 = plt.subplot(2, 2, 1)
    ax1.plot(train_df['ds'], train_df['y'], 'b-', alpha=0.5, linewidth=0.8, label='Training')
    ax1.plot(test_df['ds'], test_df['y'], 'g-', alpha=0.7, linewidth=1, label='Test Actual')
    ax1.plot(forecast['ds'], forecast['yhat'], 'r--', alpha=0.8, linewidth=1, label='Forecast')

    # Plot 95% intervals
    ax1.fill_between(
        forecast['ds'],
        forecast['yhat_lower_95'],
        forecast['yhat_upper_95'],
        alpha=0.2, color='red', label='95% Interval'
    )

    ax1.set_title('Full Forecast with 95% Prediction Intervals')
    ax1.set_xlabel('Date')
    ax1.set_ylabel('Value')
    ax1.legend(loc='upper left', fontsize=9)
    ax1.grid(True, alpha=0.3)

    # 2. Test period with calibrated intervals
    ax2 = plt.subplot(2, 2, 2)
    test_dates = calibrated_forecast['ds']

    ax2.plot(test_dates, calibrated_forecast['y'], 'g-', alpha=0.9, linewidth=1.5, label='Actual')
    ax2.plot(test_dates, calibrated_forecast['yhat'], 'r--', alpha=0.9, linewidth=1.5, label='Forecast')

    # Plot calibrated intervals if available
    if 'yhat_lower_95_cal' in calibrated_forecast.columns:
        ax2.fill_between(
            test_dates,
            calibrated_forecast['yhat_lower_95_cal'],
            calibrated_forecast['yhat_upper_95_cal'],
            alpha=0.2, color='orange', label='Calibrated 95% Interval'
        )
        # Also show original intervals for comparison
        ax2.fill_between(
            test_dates,
            calibrated_forecast['yhat_lower_95'],
            calibrated_forecast['yhat_upper_95'],
            alpha=0.1, color='red', label='Original 95% Interval'
        )
    else:
        ax2.fill_between(
            test_dates,
            calibrated_forecast['yhat_lower_95'],
            calibrated_forecast['yhat_upper_95'],
            alpha=0.2, color='red', label='95% Interval'
        )

    ax2.set_title('Test Period: Actual vs Forecast')
    ax2.set_xlabel('Date')
    ax2.set_ylabel('Value')
    ax2.legend(loc='upper left', fontsize=9)
    ax2.grid(True, alpha=0.3)

    # 3. Coverage comparison
    ax3 = plt.subplot(2, 2, 3)
    categories = ['80% Interval', '95% Interval']
    initial = [metrics['coverage_80_initial']*100, metrics['coverage_95_initial']*100]

    if 'coverage_80_calibrated' in calibration_info:
        calibrated = [calibration_info['coverage_80_calibrated']*100,
                     calibration_info['coverage_95_calibrated']*100]
        targets = [80, 95]

        x = np.arange(len(categories))
        width = 0.25

        bars1 = ax3.bar(x - width, initial, width, label='Initial', color='skyblue')
        bars2 = ax3.bar(x, calibrated, width, label='Calibrated', color='lightgreen')
        bars3 = ax3.bar(x + width, targets, width, label='Target', color='orange', alpha=0.6)

        # Add value labels
        for bars in [bars1, bars2, bars3]:
            for bar in bars:
                height = bar.get_height()
                ax3.text(bar.get_x() + bar.get_width()/2., height,
                        f'{height:.1f}%', ha='center', va='bottom', fontsize=8)
    else:
        ax3.bar(categories, initial, color='skyblue', alpha=0.7)
        ax3.axhline(y=80, color='orange', linestyle='--', alpha=0.5, label='80% Target')
        ax3.axhline(y=95, color='red', linestyle='--', alpha=0.5, label='95% Target')
        ax3.legend()

    ax3.set_xlabel('Prediction Interval')
    ax3.set_ylabel('Empirical Coverage (%)')
    ax3.set_title('Coverage Rates Comparison')
    ax3.grid(True, alpha=0.3, axis='y')

    # 4. Residual analysis
    ax4 = plt.subplot(2, 2, 4)
    residuals = test_forecast['y'] - test_forecast['yhat']

    # Histogram of residuals