def generate_timeseries_data(n_samples=2000, seq_length=60, horizon=7, n_features=5):
    """
    Generate synthetic time series data suitable for deep learning.

    Parameters:
    - n_samples: Total number of samples
    - seq_length: Lookback window for LSTM
    - horizon: Forecast horizon
    - n_features: Number of features including target

    Returns:
    - X_train, y_train, X_test, y_test
    """
    print(f"\n{'='*60}")
    print("GENERATING SYNTHETIC TIME SERIES DATA")
    print('='*60)

    # Generate timestamps
    dates = pd.date_range(start='2022-01-01', periods=n_samples, freq='H')

    # 1. Main trend component
    trend = np.linspace(0, 100, n_samples)

    # 2. Multiple seasonalities
    # Daily seasonality (24 hours)
    daily = 20 * np.sin(2 * np.pi * np.arange(n_samples) / 24)

    # Weekly seasonality (168 hours)
    weekly = 15 * np.sin(2 * np.pi * np.arange(n_samples) / (24*7))

    # Yearly seasonality (365*24 hours)
    yearly = 10 * np.sin(2 * np.pi * np.arange(n_samples) / (24*365))

    # 3. External features
    temperature = 20 + 10 * np.sin(2 * np.pi * np.arange(n_samples) / (24*365)) + np.random.normal(0, 3, n_samples)
    humidity = 50 + 20 * np.sin(2 * np.pi * np.arange(n_samples) / (24*30)) + np.random.normal(0, 5, n_samples)
    pressure = 1000 + 10 * np.sin(2 * np.pi * np.arange(n_samples) / (24*180)) + np.random.normal(0, 2, n_samples)

    # 4. Combine to create target variable
    y = trend + daily + weekly + yearly + 0.5*temperature + 0.3*humidity + 0.1*pressure

    # Add noise
    y += np.random.normal(0, 5, n_samples)

    # 5. Create feature matrix
    features = np.column_stack([y, temperature, humidity, pressure])

    # Create sequences for LSTM
    X, y_seq = [], []
    for i in range(len(features) - seq_length - horizon):
        X.append(features[i:i+seq_length])
        y_seq.append(y[i+seq_length:i+seq_length+horizon])

    X = np.array(X)
    y_seq = np.array(y_seq)

    # Split into train/test
    split_idx = int(0.8 * len(X))
    X_train, X_test = X[:split_idx], X[split_idx:]
    y_train, y_test = y_seq[:split_idx], y_seq[split_idx:]

    # Scale the data
    scaler_X = MinMaxScaler()
    scaler_y = MinMaxScaler()

    # Reshape for scaling
    X_train_reshaped = X_train.reshape(-1, X_train.shape[-1])
    X_test_reshaped = X_test.reshape(-1, X_test.shape[-1])

    # Fit on training data
    X_train_scaled = scaler_X.fit_transform(X_train_reshaped).reshape(X_train.shape)
    X_test_scaled = scaler_X.transform(X_test_reshaped).reshape(X_test.shape)

    y_train_reshaped = y_train.reshape(-1, 1)
    y_test_reshaped = y_test.reshape(-1, 1)

    y_train_scaled = scaler_y.fit_transform(y_train_reshaped).reshape(y_train.shape)
    y_test_scaled = scaler_y.transform(y_test_reshaped).reshape(y_test.shape)

    print(f"Generated {len(X)} sequences")
    print(f"Sequence length (lookback): {seq_length}")
    print(f"Forecast horizon: {horizon}")
    print(f"Number of features: {n_features}")
    print(f"Training samples: {len(X_train)}")
    print(f"Testing samples: {len(X_test)}")
    print(f"Input shape: {X_train_scaled.shape}")
    print(f"Output shape: {y_train_scaled.shape}")

    return X_train_scaled, y_train_scaled, X_test_scaled, y_test_scaled, scaler_y

