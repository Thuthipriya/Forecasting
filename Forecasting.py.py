def create_hybrid_lstm_attention_model(input_shape, horizon, n_features):
    """
    Create a hybrid LSTM-Attention model for time series forecasting.

    Architecture:
    1. LSTM layers for temporal pattern learning
    2. Multi-head attention for focusing on important timesteps
    3. Dense layers for final prediction
    """
    print(f"\n{'='*60}")
    print("BUILDING HYBRID LSTM-ATTENTION MODEL")
    print('='*60)

    inputs = layers.Input(shape=input_shape)

    # Part 1: LSTM layers for sequence processing
    x = layers.LSTM(128, return_sequences=True, dropout=0.2)(inputs)
    x = layers.LSTM(64, return_sequences=True, dropout=0.2)(x)

    # Part 2: Multi-head Attention mechanism
    attention_output = layers.MultiHeadAttention(
        num_heads=4,
        key_dim=32,
        dropout=0.1
    )(x, x)  # Self-attention

    # Add & Norm (Transformer-style)
    x = layers.Add()([x, attention_output])
    x = layers.LayerNormalization(epsilon=1e-6)(x)

    # Part 3: Feature extraction
    x = layers.Conv1D(32, kernel_size=3, padding='same', activation='relu')(x)
    x = layers.GlobalAveragePooling1D()(x)

    # Part 4: Dense layers for prediction
    x = layers.Dense(64, activation='relu')(x)
    x = layers.Dropout(0.2)(x)
    x = layers.Dense(32, activation='relu')(x)

    # Output layer (predict horizon steps)
    outputs = layers.Dense(horizon)(x)

    model = Model(inputs=inputs, outputs=outputs)

    # Compile model
    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=0.001),
        loss='mse',
        metrics=['mae']
    )

    model.summary()
    return model

