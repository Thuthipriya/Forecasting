def evaluate_model(model, X_test, y_test, scaler, model_name):
    """
    Evaluate model performance and return metrics.
    """
    print(f"\nEvaluating {model_name}...")

    # Make predictions
    y_pred_scaled = model.predict(X_test, verbose=0)

    # Inverse transform predictions
    y_pred_reshaped = y_pred_scaled.reshape(-1, 1)
    y_pred = scaler.inverse_transform(y_pred_reshaped).reshape(y_pred_scaled.shape)

    # Inverse transform actual values
    y_actual_reshaped = y_test.reshape(-1, 1)
    y_actual = scaler.inverse_transform(y_actual_reshaped).reshape(y_test.shape)

    # Calculate metrics for each forecast horizon
    metrics = {}

    # For each horizon step
    for h in range(y_test.shape[1]):
        y_actual_h = y_actual[:, h]
        y_pred_h = y_pred[:, h]

        # Calculate metrics
        mae = mean_absolute_error(y_actual_h, y_pred_h)
        rmse = np.sqrt(mean_squared_error(y_actual_h, y_pred_h))
        mape = np.mean(np.abs((y_actual_h - y_pred_h) / y_actual_h)) * 100

        # Calculate directional accuracy
        actual_direction = np.diff(y_actual_h) > 0
        pred_direction = np.diff(y_pred_h) > 0
        directional_accuracy = np.mean(actual_direction == pred_direction) * 100 if len(actual_direction) > 0 else 0

        metrics[f'horizon_{h+1}'] = {
            'MAE': mae,
            'RMSE': rmse,
            'MAPE': mape,
            'Directional_Accuracy': directional_accuracy
        }

    # Overall metrics (average across horizons)
    y_actual_flat = y_actual.flatten()
    y_pred_flat = y_pred.flatten()

    metrics['overall'] = {
        'MAE': mean_absolute_error(y_actual_flat, y_pred_flat),
        'RMSE': np.sqrt(mean_squared_error(y_actual_flat, y_pred_flat)),
        'MAPE': np.mean(np.abs((y_actual_flat - y_pred_flat) / y_actual_flat)) * 100,
        'Directional_Accuracy': np.mean(
            (np.diff(y_actual_flat) > 0) == (np.diff(y_pred_flat) > 0)
        ) * 100 if len(y_actual_flat) > 1 else 0
    }

    return metrics, y_pred, y_actual

