def visualize_attention(model, X_sample, seq_length):
    """
    Visualize attention weights to understand what the model focuses on.
    """
    print(f"\n{'='*60}")
    print("ATTENTION MECHANISM VISUALIZATION")
    print('='*60)

    try:
        # Create a model that outputs attention weights
        attention_layer = model.get_layer('multi_head_attention')

        # Get attention outputs
        attention_model = Model(
            inputs=model.input,
            outputs=attention_layer.output
        )

        # Get attention weights for a sample
        sample = X_sample[np.newaxis, ...]
        attention_output = attention_model.predict(sample, verbose=0)

        # Visualize attention weights
        fig, ax = plt.subplots(figsize=(10, 8))

        # For multi-head attention, we have multiple attention heads
        if len(attention_output.shape) == 4:
            # Take first head for visualization
            attention_weights = attention_output[0, :, :, 0]
        else:
            attention_weights = attention_output[0]

        # Plot attention heatmap
        im = ax.imshow(attention_weights, cmap='viridis', aspect='auto')
        ax.set_xlabel('Key Sequence Position')
        ax.set_ylabel('Query Sequence Position')
        ax.set_title('Attention Weights Heatmap (First Head)')

        # Add colorbar
        plt.colorbar(im, ax=ax)

        # Add timestep labels
        ax.set_xticks(np.arange(seq_length))
        ax.set_yticks(np.arange(seq_length))
        ax.set_xticklabels([f't-{seq_length-i}' for i in range(seq_length)])
        ax.set_yticklabels([f't-{seq_length-i}' for i in range(seq_length)])

        plt.tight_layout()
        plt.savefig('attention_visualization.png', dpi=150, bbox_inches='tight')
        plt.show()

        print("Attention visualization saved to 'attention_visualization.png'")

    except Exception as e:
        print(f"Could not extract attention weights: {e}")
        print("Creating simplified attention analysis...")

        # Alternative: Analyze which timesteps are most important
        feature_importance = np.std(X_sample, axis=1)

        fig, ax = plt.subplots(figsize=(10, 6))
        ax.bar(range(len(feature_importance)), feature_importance)
        ax.set_xlabel('Timestep (from oldest to newest)')
        ax.set_ylabel('Feature Variability')
        ax.set_title('Input Sequence Importance Analysis')
        ax.grid(True, alpha=0.3)
        plt.tight_layout()
        plt.savefig('sequence_importance.png', dpi=150, bbox_inches='tight')
        plt.show()

        print("Sequence importance analysis saved to 'sequence_importance.png'")

