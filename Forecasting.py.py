def create_comparison_table(hybrid_metrics, simple_metrics):
    """
    Create a comparison table of model performance.
    """
    print(f"\n{'='*60}")
    print("MODEL PERFORMANCE COMPARISON")
    print('='*60)

    comparison_data = []

    # Compare overall metrics
    for metric in ['MAE', 'RMSE', 'MAPE', 'Directional_Accuracy']:
        hybrid_val = hybrid_metrics['overall'][metric]
        simple_val = simple_metrics['overall'][metric]

        # Calculate improvement
        if metric in ['MAE', 'RMSE', 'MAPE']:
            improvement = ((simple_val - hybrid_val) / simple_val) * 100
            direction = "↓" if improvement > 0 else "↑"
        else:  # Directional Accuracy
            improvement = ((hybrid_val - simple_val) / simple_val) * 100
            direction = "↑" if improvement > 0 else "↓"

        comparison_data.append({
            'Metric': metric,
            'Hybrid Model': f"{hybrid_val:.4f}",
            'Simple LSTM': f"{simple_val:.4f}",
            'Improvement': f"{improvement:.2f}% {direction}",
            'Better': 'Hybrid' if (
                (metric in ['MAE', 'RMSE', 'MAPE'] and hybrid_val < simple_val) or
                (metric == 'Directional_Accuracy' and hybrid_val > simple_val)
            ) else 'LSTM'
        })

    # Create DataFrame
    comparison_df = pd.DataFrame(comparison_data)

    # Display table
    print("\n" + comparison_df.to_string(index=False))

    return comparison_df

